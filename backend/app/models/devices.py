class DeviceScreenshot(TenantModel):
    """
    A single on-demand screen capture from a device.

    Deliberately on-demand only — the agent captures a screenshot when an
    admin explicitly requests one (queued via pending_actions, same
    mechanism as lock/restart), not on a continuous timer. Continuous
    screen recording is a much bigger privacy/consent/legal surface than
    this project needs to take on; point-in-time captures triggered by a
    specific admin action, with that admin's identity recorded, keeps
    this auditable and defensible as an IT-support tool rather than
    surveillance software.
    """
    __tablename__ = "device_screenshots"

    device_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("devices.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    storage_key: Mapped[str] = mapped_column(String(500), nullable=False)
    mime_type: Mapped[str] = mapped_column(String(50), nullable=False, default="image/png")
    file_size_bytes: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    width: Mapped[int | None] = mapped_column(Integer, nullable=True)
    height: Mapped[int | None] = mapped_column(Integer, nullable=True)
    captured_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, index=True
    )
    requested_by_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        comment="Who asked for this capture — kept for audit purposes",
    )


class DeviceAlertType(str, enum.Enum):
    FLAGGED_APP_USAGE = "flagged_app_usage"       # active window/app title matched the watch-list
    FLAGGED_BROWSING = "flagged_browsing"         # a visited domain matched the watch-list


class DeviceAlert(TenantModel):
    """
    A flagged, non-work-activity event on a device — either an active
    window/application title or a browsed domain matching an
    organization-configured watch-list (see `activity_watchlist` in
    core/config.py).

    IMPORTANT — scope boundary, read before extending this model:
    This table intentionally does NOT store a full activity or browsing
    log. It stores only the events that matched a configured watch-list
    entry (e.g., "visited a known social-media domain during work
    hours"), never the employee's complete window-usage or browsing
    history. Capturing everything a device does — every URL visited,
    every window title, personal searches, banking, health, job-hunting
    activity, etc. — is a materially larger privacy intrusion than
    catching policy violations, carries far greater legal exposure
    (GDPR Art. 5 data-minimization, many US state monitoring-disclosure
    laws, employee-privacy statutes in several jurisdictions), and is not
    necessary to serve the stated business need. If a future requirement
    genuinely needs full activity logging, that decision should be made
    explicitly, with legal review, as a new and clearly-labeled
    capability — not accreted onto this table.

    Legal/compliance note (not legal advice — consult counsel per
    jurisdiction): device monitoring of this kind typically requires the
    organization to give employees clear advance notice of what is
    monitored and why (see the agent's first-run consent notice and the
    always-visible system tray indicator). Several jurisdictions require
    more than notice — e.g., a documented legitimate-interest basis under
    GDPR, or two-party consent for some forms of monitoring. Do not
    enable this feature for an organization without confirming their
    disclosure/consent obligations have been met.
    """
    __tablename__ = "device_alerts"

    device_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("devices.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    alert_type: Mapped[DeviceAlertType] = mapped_column(
        SAEnum(DeviceAlertType, name="device_alert_type_enum"), nullable=False, index=True
    )
    matched_term: Mapped[str] = mapped_column(
        String(200), nullable=False, comment="The watch-list entry that matched (e.g. 'facebook.com')"
    )
    detail: Mapped[str] = mapped_column(
        String(500), nullable=False,
        comment="Window title for flagged_app_usage, or the matched domain for flagged_browsing — never a full URL with path/query, to avoid capturing search terms or personal content in links",
    )
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)
    is_acknowledged: Mapped[bool] = mapped_column(Boolean, default=False, server_default="false", nullable=False)


class DeviceAllowedApp(TenantModel):
    """
    A per-device override that suppresses flagged-activity alerts for one
    specific app/domain, on one specific device.

    This sits ABOVE the global watch-list (settings.DEVICE_ACTIVITY_WATCHLIST):
    if "whatsapp.com" is in the org's global watch-list but this table has
    a row for (device_X, "whatsapp.com"), device_X never generates an
    alert for WhatsApp, while every other device still does. Use case:
    an employee who's approved to use WhatsApp for work communication
    shouldn't keep tripping the same alert every day.

    Checked at alert-*creation* time in the upload_alerts endpoint, not
    on the agent — the agent has no idea what's allowed or not, it just
    reports every watch-list match it sees. This means an admin can
    change an allow-list entry and it takes effect immediately on the
    next upload, without touching the agent or waiting for a redeploy.
    """
    __tablename__ = "device_allowed_apps"

    device_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("devices.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    domain_or_app: Mapped[str] = mapped_column(
        String(200), nullable=False,
        comment="Normalized base label, e.g. 'whatsapp.com' — matched the same way the watch-list itself matches",
    )
    reason: Mapped[str | None] = mapped_column(String(300), nullable=True)
    allowed_by_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
        comment="Which admin granted this exception — kept for audit purposes",
    )


