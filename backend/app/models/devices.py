"""
Device and Asset Management models.

Device      — a registered endpoint (laptop, desktop, server) running the agent
DeviceMetric — time-series hardware snapshots (CPU, RAM, Disk)
Asset       — any physical IT asset (monitor, keyboard, phone, chair)
AssetAssignment — audit trail of who had what asset when
"""

